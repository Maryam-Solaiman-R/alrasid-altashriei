from backend_app import parse_uqn_text

TITLE = 'الموافقة على تعديل مواد في اللائحة التنفيذية لنظام المنافسات والمشتريات الحكومية'
TEXT = '''
1447-12-19 الموافق 05-06-2026
قرار وزير المالية رقم (1097) وتاريخ 09/12/1447هـ
يقرر الآتي:
أولًا: الموافقة على تعديل المواد (الثامنة والثمانين) و(الحادية عشرة بعد المائة) و(الرابعة عشرة بعد المائة) و(الثانية والثلاثين بعد المائة) من اللائحة التنفيذية لنظام المنافسات والمشتريات الحكومية الصادرة بالقرار الوزاري رقم (1242) وتاريخ 21/3/1441هـ، والمعدّلة بالقرارات الوزارية رقم (3479) وتاريخ 11/8/1441هـ، ورقم (451) وتاريخ 7/4/1444هـ، ورقم (1090) وتاريخ 21/9/1445هـ، وفقًا للصيغة المرافقة بهذا القرار.
ثانيًا: يُنشر هذا القرار في الجريدة الرسمية ويُعمل بموجبه ابتداءً من تاريخه.
'''

data = parse_uqn_text(TEXT, TITLE)
assert data['decision_number'] == '1097', data
assert data['decision_date_hijri'] == '09/12/1447', data
assert data['publication_date_hijri'] == '1447-12-19', data
assert data['publication_date_gregorian'] == '05-06-2026', data
assert [a['number'] for a in data['articles']] == [88,111,114,132], data['articles']
assert data['effective_rule'] == 'يُعمل بموجبه ابتداءً من تاريخه', data['effective_rule']
print('PASS')
print(data)
